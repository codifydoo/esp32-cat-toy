// Renders every image asset into assets/img and writes the C manifest used by the firmware.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CANVAS, VARIANTS, PIANO_CATS, pianoPalette, catParts } from './cat_geometry.mjs';
import { APP_ICONS, appIconSvg } from './icons.mjs';
import { UI_IMAGES } from './ui_images.mjs';
import { render, alphaBBox, unionBBox, evenBBox, crop, toLvglBin, toPng } from './raster.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const IMG_OUT = path.join(ROOT, 'assets/img');
const PREVIEW = path.join(ROOT, 'build-assets/preview');
const MANIFEST_H = path.join(ROOT, 'components/assets/include/assets_manifest.h');
const MANIFEST_C = path.join(ROOT, 'components/assets/assets_manifest.c');
const SCALES = [['S', 0.65], ['M', 1.0], ['L', 1.3]];

const svgDoc = ([x, y, w, h], inner) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${x} ${y} ${w} ${h}" width="${w}" height="${h}">${inner}</svg>`;

const written = [];
function write(name, img) {
  const bin = path.join(IMG_OUT, `${name}.bin`);
  const png = path.join(PREVIEW, `${name}.png`);
  fs.mkdirSync(path.dirname(bin), { recursive: true });
  fs.mkdirSync(path.dirname(png), { recursive: true });
  fs.writeFileSync(bin, toLvglBin(img));
  fs.writeFileSync(png, toPng(img));
  written.push(name);
}

fs.rmSync(IMG_OUT, { recursive: true, force: true });
fs.rmSync(PREVIEW, { recursive: true, force: true });

// Cat parts: one crop box per (part, scale), shared by all variants so positions never differ.
const variants = Object.keys(VARIANTS);
const pianos = Object.keys(PIANO_CATS);
const partsBy = Object.fromEntries([
  ...variants.map((v) => [v, catParts(VARIANTS[v])]),
  ...pianos.map((p) => [p, catParts(pianoPalette(PIANO_CATS[p]))]),
]);
const catRows = Object.keys(partsBy[variants[0]]).map((part) => ({
  part,
  shared: variants.every((v) => partsBy[v][part] === partsBy[variants[0]][part]),
  x: [],
  y: [],
}));
const canvas = [];
SCALES.forEach(([tag, scale], si) => {
  const width = Math.round(CANVAS.w * scale);
  for (const row of catRows) {
    // Meow piano's cats exist at S only (spec §3.11). They share the crop box, so positions never differ.
    const owners = row.shared ? ['shared'] : tag === 'S' ? [...variants, ...pianos] : variants;
    const imgs = owners.map((o) =>
      render(svgDoc([CANVAS.x, CANVAS.y, CANVAS.w, CANVAS.h], partsBy[o === 'shared' ? variants[0] : o][row.part]), width),
    );
    canvas[si] = { w: imgs[0].w, h: imgs[0].h };
    let bb = imgs.map(alphaBBox).reduce((a, b) => unionBBox(a, b), null);
    if (!bb) throw new Error(`cat part ${row.part} renders empty at ${tag}`);
    bb = evenBBox(bb, imgs[0].w, imgs[0].h);
    owners.forEach((o, i) => write(`cat/${o}/${tag}/${row.part}`, crop(imgs[i], bb)));
    row.x[si] = bb.x0;
    row.y[si] = bb.y0;
  }
});

// App icons at menu size and parent-grid size.
for (const app of APP_ICONS) {
  write(`apps/${app.key}`, render(appIconSvg(app), 240));
  write(`apps/${app.key}_96`, render(appIconSvg(app), 96));
}

// UI images; cropped ones record where their top-left belongs.
const uiRows = [];
for (const u of UI_IMAGES) {
  let img = render(svgDoc(u.viewBox, u.svg), u.size ?? u.viewBox[2]);
  let x = 0;
  let y = 0;
  if (u.crop) {
    const bb = evenBBox(alphaBBox(img), img.w, img.h);
    img = crop(img, bb);
    x = bb.x0;
    y = bb.y0;
  }
  write(u.name, img);
  uiRows.push({ name: u.name, x, y });
}

// C manifest.
const q = (s) => JSON.stringify(s);
fs.writeFileSync(
  MANIFEST_H,
  [
    '// Generated by tools/export_images/export.mjs. Do not edit.',
    '#pragma once',
    '#include <stddef.h>',
    '#include <stdint.h>',
    '',
    'typedef struct {',
    '    const char *part;',
    '    uint8_t shared; /* 1: one image for every cat variant, under "cat/shared/" */',
    '    int16_t x[3];   /* top-left inside the rendered cat canvas, per scale S, M, L */',
    '    int16_t y[3];',
    '} cat_part_pos_t;',
    '',
    'typedef struct {',
    '    const char *name;',
    '    int16_t x;',
    '    int16_t y;',
    '} ui_image_pos_t;',
    '',
    'extern const int16_t CAT_CANVAS_W[3];',
    'extern const int16_t CAT_CANVAS_H[3];',
    'extern const int16_t CAT_ORIGIN_PX[3]; /* where the design origin (0,0) sits inside the canvas */',
    'extern const cat_part_pos_t CAT_PARTS[];',
    'extern const size_t CAT_PARTS_COUNT;',
    'extern const ui_image_pos_t UI_IMAGE_POS[];',
    'extern const size_t UI_IMAGE_POS_COUNT;',
    '',
  ].join('\n'),
);
fs.writeFileSync(
  MANIFEST_C,
  [
    '// Generated by tools/export_images/export.mjs. Do not edit.',
    '#include "assets_manifest.h"',
    '',
    `const int16_t CAT_CANVAS_W[3] = {${canvas.map((c) => c.w).join(', ')}};`,
    `const int16_t CAT_CANVAS_H[3] = {${canvas.map((c) => c.h).join(', ')}};`,
    `const int16_t CAT_ORIGIN_PX[3] = {${canvas.map((c) => Math.round((-CANVAS.x * c.w) / CANVAS.w)).join(', ')}};`,
    '',
    'const cat_part_pos_t CAT_PARTS[] = {',
    ...catRows.map((r) => `    {${q(r.part)}, ${r.shared ? 1 : 0}, {${r.x.join(', ')}}, {${r.y.join(', ')}}},`),
    '};',
    `const size_t CAT_PARTS_COUNT = ${catRows.length};`,
    '',
    'const ui_image_pos_t UI_IMAGE_POS[] = {',
    ...uiRows.map((r) => `    {${q(r.name)}, ${r.x}, ${r.y}},`),
    '};',
    `const size_t UI_IMAGE_POS_COUNT = ${uiRows.length};`,
    '',
  ].join('\n'),
);

// Contact sheet for eyeballing against design/claude-design/CatSheet.dc.html.
fs.writeFileSync(
  path.join(PREVIEW, 'index.html'),
  '<!doctype html><meta charset="utf-8"><title>Asset preview</title>' +
    '<style>body{background:#000;color:#aaa;font:12px system-ui;margin:16px}figure{display:inline-block;margin:6px;text-align:center}img{background:#111}</style>' +
    written.map((n) => `<figure><img src="${n}.png"><figcaption>${n}</figcaption></figure>`).join(''),
);

const shared = catRows.filter((r) => r.shared).length;
console.log(`cat parts: ${catRows.length} (${shared} shared), images written: ${written.length}`);
